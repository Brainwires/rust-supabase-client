//! # supabase-client-sdk
//!
//! A Rust client for [Supabase](https://supabase.com/) with a fluent, Supabase JS-like API.
//! Uses the **PostgREST REST API by default** — no database connection needed. Opt into
//! direct PostgreSQL access via [sqlx](https://github.com/launchbadge/sqlx) with the
//! `direct-sql` feature flag.
//!
//! This is the main facade crate that re-exports all sub-crates behind feature flags.
//!
//! ## Quick Start
//!
//! ```rust,no_run
//! use supabase_client_sdk::prelude::*;
//!
//! #[tokio::main]
//! async fn main() -> Result<(), Box<dyn std::error::Error>> {
//!     let config = SupabaseConfig::new("https://your-project.supabase.co", "your-anon-key");
//!     let client = SupabaseClient::new(config)?;
//!
//!     let response = client.from("cities").select("*").execute().await;
//!     for row in response.into_result()? {
//!         println!("{}", row.get_as::<String>("name").unwrap());
//!     }
//!     Ok(())
//! }
//! ```
//!
//! ## Feature Flags
//!
//! | Feature | Default | Description |
//! |---------|---------|-------------|
//! | `query` | Yes | Query builder (select, insert, update, delete, upsert, rpc) |
//! | `derive` | Yes | `#[derive(Table)]` proc macro |
//! | `auth` | No | GoTrue authentication client |
//! | `realtime` | No | WebSocket realtime subscriptions |
//! | `storage` | No | Object storage client |
//! | `functions` | No | Edge Functions client |
//! | `graphql` | No | GraphQL client (pg_graphql) |
//! | `direct-sql` | No | Direct PostgreSQL via sqlx (bypasses PostgREST; not on wasm32) |
//! | `full` | No | All of the above except `direct-sql` |
//! | `rustls` | Yes | TLS via rustls (aws-lc-rs, OS trust store); no OpenSSL |
//! | `native-tls` | No | TLS via OpenSSL / SChannel / Secure Transport |
//!
//! To build without rustls, use `default-features = false` and list the
//! features you need plus `native-tls`.
//!
//! ## Acting as the signed-in user
//!
//! The auth client returned by `client.auth()` shares the `SupabaseClient`'s
//! access-token slot. After a sign-in, query, storage, functions, GraphQL and
//! realtime clients created from the same `SupabaseClient` send the user's
//! JWT as `Authorization: Bearer ...` (with the API key as `apikey`), so
//! row-level security and storage policies apply to that user. Sign-out
//! clears the slot. You can also set it yourself with
//! [`SupabaseClient::set_access_token`].

#![cfg_attr(docsrs, feature(doc_cfg))]

#[cfg(all(feature = "direct-sql", target_arch = "wasm32"))]
compile_error!(
    "the `direct-sql` feature of supabase-client-sdk is not supported on wasm32: \
     it opens PostgreSQL connections with sqlx, which needs a native TCP stack. \
     Disable `direct-sql` for wasm32 builds and use the REST query builder."
);

